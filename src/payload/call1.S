/* =============================================================================
 * CloudTrainerPayload - call1.S
 * -----------------------------------------------------------------------------
 * void ct_call1(void* fn, int arg)
 *
 * 调用一个"只带一个整型参数、调用约定未知"的外部函数。
 * HookLib!Lock 在 0x2A60 处的实现是 cdecl（末尾是裸 ret），
 * 但别的版本/别的导出完全可能是 stdcall，直接把函数指针强转成某一种约定去调
 * 会在栈不平衡时把目标进程搞崩。这里在调用前后保存/恢复 ESP，
 * 两种约定都能安全返回。
 * ========================================================================== */
    .text
    .globl _ct_call1
_ct_call1:
    movl 4(%esp), %eax      /* fn  */
    movl 8(%esp), %ecx      /* arg */
    movl %esp, %edx         /* 保存原始栈指针 */
    pushl %ecx
    call *%eax
    movl %edx, %esp         /* 不关心被调方是否清栈，直接还原 */
    ret
